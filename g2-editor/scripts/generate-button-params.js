#!/usr/bin/env node
/*
 * Generates src/renderer/buttonParams.ts from the Delphi reference editor's ModuleParams table
 * (BVE.NMG2Data.pas), which defines what the physical pushbutton below each assignable knob
 * actually targets. See the "Follow-up: Port ButtonParamIndex" plan for full context.
 *
 * Usage: node scripts/generate-button-params.js <path-to-BVE.NMG2Data.pas>
 *
 * Fully regenerates the output file from scratch every run — never hand-edit buttonParams.ts,
 * fix this script and rerun instead.
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const srcPath = process.argv[2];
if (!srcPath) {
	console.error('Usage: node scripts/generate-button-params.js <path-to-BVE.NMG2Data.pas>');
	process.exit(1);
}

const raw = fs.readFileSync(srcPath, 'utf8');

// The Delphi formatter reflows lines mid-record/mid-field, so line-based parsing is unsafe —
// collapse the whole file into one token stream first.
const flat = raw.replace(/\s+/g, ' ');

// Isolate the ModuleParams block. Non-greedy .*? is safe here: every intermediate record
// boundary is "), (", only the true final record is followed by "));".
const blockRe = /ModuleParams:\s*array\s*\[\s*0\s*\.\.\s*914\s*\]\s*of\s*TG2ModuleParamDef\s*=\s*\(\((.*?)\)\);/;
const blockMatch = flat.match(blockRe);
if (!blockMatch) throw new Error('ModuleParams block not found in source — file format may have changed');
const body = blockMatch[1];

// Field-by-field extraction (not record-splitting) — matches TG2ModuleParamDef's fixed field
// order directly. Only ModuleID/ParamIndex/ButtonParam are captured; ParamID/ParamName/
// DefaultValue/DefaultKnob/slParamLabel are matched-over to keep the regex anchored to the full
// record shape. "-?\s*\d+" tolerates Delphi's "- 1" (space after unary minus) as well as "-1".
// "'(?:''|[^'])*'" correctly skips ParamName even with escaped '' apostrophes inside it.
const fieldRe =
	/ModuleID:\s*(\d+)\s*;\s*ParamIndex:\s*(\d+)\s*;\s*ParamID:\s*-?\s*\d+\s*;\s*ParamName:\s*'(?:''|[^'])*'\s*;\s*DefaultValue:\s*-?\s*\d+\s*;\s*DefaultKnob:\s*-?\s*\d+\s*;\s*ButtonParam:\s*(-?\s*\d+)\s*;/g;

const entries = [];
let m;
while ((m = fieldRe.exec(body)) !== null) {
	entries.push({
		moduleId: parseInt(m[1], 10),
		paramIndex: parseInt(m[2], 10),
		buttonParam: parseInt(m[3].replace(/\s+/g, ''), 10),
	});
}

// ---- Structural validation (fail fast, before writing anything) ----
function expect(cond, msg) {
	if (!cond) throw new Error('Validation failed: ' + msg);
}

expect(entries.length === 915, `expected 915 entries, got ${entries.length}`);

const byKey = new Map(entries.map((e) => [`${e.moduleId}:${e.paramIndex}`, e.buttonParam]));
expect(byKey.get('4:0') === 0, 'module 4 param 0 should self-mirror (0)');
expect(byKey.get('4:1') === 1, 'module 4 param 1 should self-mirror (1)');
expect(byKey.get('4:2') === 2, 'module 4 param 2 should self-mirror (2)');
expect(byKey.get('3:0') === -1, 'module 3 param 0 should have no button (-1)');
expect(byKey.get('7:0') === 4, 'module 7 param 0 should target button param 4');
expect(byKey.get('7:1') === 2, 'module 7 param 1 should target button param 2');
expect(byKey.get('145:0') === 16, 'module 145 param 0 (Seq1Step1) should target button param 16');
expect(byKey.get('145:16') === 16, 'module 145 param 16 (Seq2Step1) should self-mirror (16)');

// ---- Build the deviations-only table ----
// ModuleModes (a separate, smaller table) is deliberately not parsed: this port's Parameter
// Pages system only ever assigns from ModuleDefinition.params, never .modes.
const byModule = new Map();
for (const e of entries) {
	if (e.buttonParam === e.paramIndex) continue; // self-mirror — already the default, omit
	if (!byModule.has(e.moduleId)) byModule.set(e.moduleId, new Map());
	byModule.get(e.moduleId).set(e.paramIndex, e.buttonParam);
}

const moduleIds = [...byModule.keys()].sort((a, b) => a - b);
const lines = moduleIds.map((moduleId) => {
	const params = byModule.get(moduleId);
	const paramIndices = [...params.keys()].sort((a, b) => a - b);
	const entryStr = paramIndices.map((pi) => `${pi}: ${params.get(pi)}`).join(', ');
	return `\t${moduleId}: { ${entryStr} },`;
});

const deviationCount = entries.filter((e) => e.buttonParam !== e.paramIndex).length;

const output = `// Generated by scripts/generate-button-params.js from BVE.NMG2Data.pas (Delphi reference editor).
// Do not hand-edit — rerun the generator instead.
//
// Stores only DEVIATIONS from the default "button mirrors its own knob param" behavior:
//   -1                 = this param has no button function at all
//   a different number = the paramIndex (on the same module) the button actually targets
// A (moduleId, paramIndex) pair absent from this table means "mirrors its own param" (the
// existing default in ParameterPages.vue) — most params (~42%) fall in this bucket and are
// intentionally omitted. ModuleModes pseudo-params are out of scope: Parameter Pages only ever
// assigns from ModuleDefinition.params, never .modes.

// prettier-ignore
const buttonParams: Record<number, Record<number, number>> = {
${lines.join('\n')}
};

export function getButtonParamIndex(moduleId: number, paramIndex: number): number | undefined {
	return buttonParams[moduleId]?.[paramIndex];
}

export function getButtonParamModuleIds(): number[] {
	return Object.keys(buttonParams).map(Number);
}

export function getButtonParamsForModule(moduleId: number): Record<number, number> | undefined {
	return buttonParams[moduleId];
}
`;

const outPath = path.join(__dirname, '..', 'src', 'renderer', 'buttonParams.ts');
fs.writeFileSync(outPath, output);
execSync(`npx prettier --write "${outPath}"`, { stdio: 'inherit' });

console.log(`Wrote ${outPath}: ${entries.length} entries parsed, ${deviationCount} deviations across ${moduleIds.length} modules.`);
