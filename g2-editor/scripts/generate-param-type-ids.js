#!/usr/bin/env node
/*
 * Generates src/renderer/paramTypeIds.ts: the official editor's param-type id for every module
 * param, read from the Mac v1.62 editor binary. Used by the Patch Mutator (curves, Quick Lock
 * categories, permanently locked params) and the Patch Adjuster (knob mapping).
 *
 * Usage: node scripts/generate-param-type-ids.js "<path>/Nord Modular G2 OS v1.62 Update.dmg"
 *
 * Layout (i386 slice): `_k<Name>ModuleInfo` +0x00 module type, +0x04 ParamData ptr,
 * +0x18 param count (byte). ParamData record stride 0x1c: name[11] +0x00, max +0x0b,
 * default +0x0c, official param-type id +0x12. Record order = nmg2mods.ts params order.
 *
 * Fully regenerates the output file — never hand-edit paramTypeIds.ts.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const dmg = process.argv[2];
if (!dmg) {
	console.error('Usage: node scripts/generate-param-type-ids.js <path-to-v1.62-update.dmg>');
	process.exit(1);
}

const work = fs.mkdtempSync(path.join(os.tmpdir(), 'g2-param-types-'));
const mnt = path.join(work, 'mnt');
const bin = path.join(work, 'editor-i386');
fs.mkdirSync(mnt);
execFileSync('hdiutil', ['attach', '-readonly', '-nobrowse', '-mountpoint', mnt, dmg], { stdio: 'ignore' });
try {
	execFileSync('lipo', ['-thin', 'i386', path.join(mnt, 'Nord Modular G2 Editor.app/Contents/MacOS/Nord Modular G2 Editor'), '-output', bin]);
} finally {
	execFileSync('hdiutil', ['detach', mnt], { stdio: 'ignore' });
}

// vm address → file offset, from the LC_SEGMENT load commands
const segs = [];
for (const block of execFileSync('otool', ['-l', bin], { encoding: 'utf8' }).split('Load command').slice(1)) {
	if (!/cmd LC_SEGMENT\n/.test(block)) continue;
	const num = (k) => Number(block.match(new RegExp(`\\n\\s*${k} (\\S+)`))[1]);
	segs.push({ vm: num('vmaddr'), size: num('vmsize'), off: num('fileoff') });
}
const fileOff = (addr) => {
	const s = segs.find((s) => addr >= s.vm && addr < s.vm + s.size);
	if (!s) throw new Error(`address 0x${addr.toString(16)} not in any segment`);
	return s.off + addr - s.vm;
};

const data = fs.readFileSync(bin);
const table = new Map();
for (const line of execFileSync('nm', [bin], { encoding: 'utf8', maxBuffer: 64 << 20 }).split('\n')) {
	const m = line.match(/^([0-9a-f]+) [sSdD] _k(\w+)ModuleInfo$/);
	if (!m) continue;
	const info = fileOff(parseInt(m[1], 16));
	const type = data.readUInt32LE(info);
	const count = data[info + 0x18];
	const params = data.readUInt32LE(info + 4);
	const ids = [];
	for (let p = 0; p < count; p++) ids.push(data[fileOff(params) + p * 0x1c + 0x12]);
	table.set(type, { name: m[2], ids });
}
fs.rmSync(work, { recursive: true, force: true });

const hex = (n) => `0x${n.toString(16).padStart(2, '0')}`;
const lines = [...table.entries()]
	.sort((a, b) => a[0] - b[0])
	.filter(([, v]) => v.ids.length > 0)
	.map(([type, v]) => `\t${type}: [${v.ids.map(hex).join(', ')}], // ${v.name}`);

const out = `// GENERATED by scripts/generate-param-type-ids.js from the official Mac editor v1.62 — do not edit.
// Official param-type id per module param (index = nmg2mods.ts param index), keyed by module type.
export const PARAM_TYPE_IDS: Record<number, number[]> = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(__dirname, '../src/renderer/paramTypeIds.ts'), out);
console.log(`Wrote ${lines.length} modules`);
