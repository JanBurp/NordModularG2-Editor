import { useSlotsStore } from '../store/slots';
import { useUiStore } from '../store/ui';
import { getModule } from '../renderer/nmg2mods';
import { isNestDrivenByOutput } from '../parser/cableGraph';
import { getEffectiveJackColor, MODULE_WIDTH } from '../constants';
import { useJackPatching } from './useJackPatching';
import pairStats from '../renderer/cablePairStats.json';
import type { Cable } from '../renderer/cableRenderer';

export type GhostJack = { moduleIndex: number; connectorIndex: number; type: 'input' | 'output'; colour: string };
export type GhostPoint = { x: number; y: number };
export type GhostPair = { from: GhostJack; to: GhostJack };
// `extra` is a second cable: of a stereo suggestion (e.g. R->R, or a mono output feeding both inputs), or
// the new->below half of a rewire. `replaces` is the existing cable a rewire removes on confirm.
export type GhostCandidate = GhostPair & { extra?: GhostPair; replaces?: Cable };
export type GhostCable = { area: 0 | 1; from: GhostJack; to: GhostJack | GhostPoint; extra?: GhostPair; replaces?: Cable };

export function isGhostJack(to: GhostJack | GhostPoint): to is GhostJack {
	return 'moduleIndex' in to;
}

// How often each output->input pair is cabled within a column (source above destination) in a large
// set of real patches, pairs seen >= 5 times only. Generated by scripts/generate-cable-pair-stats.js.
const pairCounts = new Map((pairStats as number[][]).map(([srcType, out, dstType, inp, n]) => [`${srcType}:${out}:${dstType}:${inp}`, n]));
const pairCount = (src: any, out: number, dst: any, inp: number): number => pairCounts.get(`${src.type}:${out}:${dst.type}:${inp}`) ?? 0;

// A Dynamic jack's colour can flip when its module is uprated (see getEffectiveJackColor): purple -> red,
// orange -> orange (from yellow). Two jacks are considered the same "family" if they'd display the same
// colour once uprated, so a currently-blue purple input still counts as a match for a red output.
function colourFamily(colour: string): string {
	return getEffectiveJackColor(colour, true);
}

type IndexedJack = { jack: any; idx: number };

const indexed = (jacks: any[] | undefined): IndexedJack[] => (jacks ?? []).map((jack, idx) => ({ jack, idx }));

// Auto-suggest only considers audio-rate jacks (red, or purple which can be uprated to red) in the
// right third of the module, where Osc/Filter/FX/Level/Mixer/... keep their audio inputs and outputs.
function isAudioJackOnRight(jack: any): boolean {
	return colourFamily(jack.colour) === 'red' && jack.x >= (MODULE_WIDTH * 2) / 3;
}

// Groups jacks into stereo pairs (names X+'L' / X+'R', e.g. InL/InR, In1L/In1R) and single jacks.
function toUnits(jacks: IndexedJack[]): IndexedJack[][] {
	const units: IndexedJack[][] = [];
	const paired = new Set<number>();
	for (const left of jacks) {
		const right = left.jack.name.endsWith('L') ? jacks.find((j) => j.jack.name === `${left.jack.name.slice(0, -1)}R`) : undefined;
		if (!right) continue;
		units.push([left, right]);
		paired.add(left.idx).add(right.idx);
	}
	return [...units, ...jacks.filter((j) => !paired.has(j.idx)).map((j) => [j])];
}

const unitY = (unit: IndexedJack[]) => Math.min(...unit.map((j) => j.jack.y));

const moduleHeight = (m: any): number => getModule(m.type)?.height ?? 2;

// Nearest module in column `col` ending at/above `row` ('above'), or starting at/below `row` ('below').
function nearestInColumn(modules: any[], col: number, row: number, dir: 'above' | 'below', excludeIndex: number): any {
	const fits = (m: any) => m.index !== excludeIndex && m.horiz === col && (dir === 'above' ? m.vert + moduleHeight(m) <= row : m.vert >= row);
	const closer = (m: any, best: any) => (dir === 'above' ? m.vert > best.vert : m.vert < best.vert);
	return modules.filter(fits).reduce((best: any, m: any) => (!best || closer(m, best) ? m : best), null);
}

const ghostJack = (mod: any, j: IndexedJack, type: 'input' | 'output'): GhostJack => ({
	moduleIndex: mod.index,
	connectorIndex: j.idx,
	type,
	colour: getEffectiveJackColor(j.jack.colour, mod.uprate === 1),
});
const ghostPair = (src: any, out: IndexedJack, dst: any, inp: IndexedJack): GhostPair => ({
	from: ghostJack(src, out, 'output'),
	to: ghostJack(dst, inp, 'input'),
});

// Audio cable(s) from sourceMod's outputs into targetMod's free inputs, one candidate per (output unit,
// input unit), see toUnits: inputs top-first, outputs bottom-first (module layouts put the main audio in at
// top-right and out at bottom-right). A stereo input gets two cables: L->L and R->R from a stereo output,
// or the single output into both L and R.
function audioCandidates(sourceMod: any, targetMod: any, cables: Cable[]): GhostCandidate[] {
	const outputs = indexed(getModule(sourceMod.type)?.outputs).filter(({ jack }) => isAudioJackOnRight(jack));
	const freeInputs = indexed(getModule(targetMod.type)?.inputs).filter(
		({ jack, idx }) => isAudioJackOnRight(jack) && !isNestDrivenByOutput(cables, targetMod.index, idx),
	);
	const outUnits = toUnits(outputs).sort((a, b) => unitY(b) - unitY(a));
	return toUnits(freeInputs)
		.sort((a, b) => unitY(a) - unitY(b))
		.flatMap(([inL, inR]) =>
			outUnits.map(([outL, outR]) => {
				const first = ghostPair(sourceMod, outL, targetMod, inL);
				return inR ? { ...first, extra: ghostPair(sourceMod, outR ?? outL, targetMod, inR) } : first;
			}),
		);
}

// Any-colour cables from src into dst's free inputs that real patches use (see pairCounts), most common first.
function tableCandidates(src: any, dst: any, cables: Cable[]): GhostCandidate[] {
	const outputs = indexed(getModule(src.type)?.outputs);
	return indexed(getModule(dst.type)?.inputs)
		.filter(({ idx }) => !isNestDrivenByOutput(cables, dst.index, idx))
		.flatMap((inp) => outputs.map((out) => ({ out, inp, n: pairCount(src, out.idx, dst, inp.idx) })))
		.filter(({ n }) => n > 0)
		.sort((a, b) => b.n - a.n)
		.map(({ out, inp }) => ghostPair(src, out, dst, inp));
}

// The new module dropped between `above` and `below` that are cabled to each other: rewire each such cable
// through it (above -> new -> below), using the new module's jacks of the cable's colour. Ranked by
// pairCounts, then position (inputs top-first, outputs bottom-first).
function rewireCandidates(above: any, newMod: any, below: any, cables: Cable[]): GhostCandidate[] {
	const aboveDef = getModule(above.type);
	const belowDef = getModule(below.type);
	const def = getModule(newMod.type);
	return cables
		.filter((c) => (c.dir ?? 1) === 1 && c.smod === above.index && c.dmod === below.index)
		.flatMap((c) => {
			const aboveOut = { jack: aboveDef?.outputs?.[c.scon], idx: c.scon };
			const belowIn = { jack: belowDef?.inputs?.[c.dcon], idx: c.dcon };
			if (!aboveOut.jack || !belowIn.jack) return [];
			const family = colourFamily(aboveOut.jack.colour);
			const sameFamily = (j: IndexedJack) => colourFamily(j.jack.colour) === family;
			const inputs = indexed(def?.inputs).filter(sameFamily);
			const outputs = indexed(def?.outputs).filter(sameFamily);
			return inputs
				.flatMap((inp) =>
					outputs.map((out) => ({ inp, out, n: pairCount(above, c.scon, newMod, inp.idx) + pairCount(newMod, out.idx, below, c.dcon) })),
				)
				.sort((a, b) => b.n - a.n || a.inp.jack.y - b.inp.jack.y || b.out.jack.y - a.out.jack.y)
				.map(({ inp, out }) => ({ ...ghostPair(above, aboveOut, newMod, inp), extra: ghostPair(newMod, out, below, belowIn), replaces: c }));
		});
}

const candidateKey = (c: GhostCandidate): string =>
	[c.from, c.to, c.extra?.from, c.extra?.to].map((j) => (j ? `${j.moduleIndex}.${j.type}.${j.connectorIndex}` : '')).join('|');

export function useGhostCable() {
	const slotsStore = useSlotsStore();
	const uiStore = useUiStore();
	const { connectJacks } = useJackPatching();

	function showCandidates(candidates: GhostCandidate[], areaIdx: 0 | 1): void {
		if (candidates.length === 0) {
			uiStore.ghostCable = null;
			return;
		}
		uiStore.ghostCandidates = candidates;
		uiStore.ghostCandidateIndex = 0;
		uiStore.ghostCable = { area: areaIdx, ...candidates[0] };
	}

	// Uses the nearest modules above and below the new one in the same column (gaps in between are allowed).
	// Candidates, best first: rewire an above->below cable through the new module; audio above->new; then
	// any-colour above->new and new->below pairs that real patches use.
	function computeGhostSuggestion(newModuleIndex: number, col: number, row: number, area: 'va' | 'fx'): void {
		const areaIdx: 0 | 1 = area === 'va' ? 1 : 0;
		const modules = slotsStore.getAreaModules(uiStore.slotInFocus, areaIdx);
		const newMod = modules.find((m: any) => m.index === newModuleIndex);
		if (!newMod || !getModule(newMod.type)) {
			uiStore.ghostCable = null;
			return;
		}
		const above = nearestInColumn(modules, col, row, 'above', newModuleIndex);
		const below = nearestInColumn(modules, col, row + moduleHeight(newMod), 'below', newModuleIndex);
		const cables = slotsStore.getAreaCables(uiStore.slotInFocus, areaIdx);
		const candidates = [
			...(above && below ? rewireCandidates(above, newMod, below, cables) : []),
			...(above ? audioCandidates(above, newMod, cables) : []),
			...(above ? tableCandidates(above, newMod, cables) : []),
			...(below ? tableCandidates(newMod, below, cables) : []),
		];
		showCandidates([...new Map(candidates.map((c) => [candidateKey(c), c])).values()], areaIdx);
	}

	// After deleting a module that was cabled audio-wise between the nearest module above and below it
	// (same column), proposes bridging above -> below. cablesBefore is the area's cable list before the delete.
	function suggestAfterDelete(deleted: any, cablesBefore: Cable[], area: 'va' | 'fx'): void {
		const areaIdx: 0 | 1 = area === 'va' ? 1 : 0;
		const modules = slotsStore.getAreaModules(uiStore.slotInFocus, areaIdx);
		const above = nearestInColumn(modules, deleted.horiz, deleted.vert, 'above', deleted.index);
		const below = nearestInColumn(modules, deleted.horiz, deleted.vert + moduleHeight(deleted), 'below', deleted.index);
		const linked = (c: Cable) => (c.dir ?? 1) === 1;
		const fromAbove =
			above &&
			cablesBefore.some(
				(c) => linked(c) && c.smod === above.index && c.dmod === deleted.index && isAudioJackOnRight(getModule(above.type)?.outputs?.[c.scon] ?? {}),
			);
		const intoBelow =
			below &&
			cablesBefore.some(
				(c) => linked(c) && c.smod === deleted.index && c.dmod === below.index && isAudioJackOnRight(getModule(below.type)?.inputs?.[c.dcon] ?? {}),
			);
		if (!fromAbove || !intoBelow) {
			uiStore.ghostCable = null;
			return;
		}
		showCandidates(audioCandidates(above, below, slotsStore.getAreaCables(uiStore.slotInFocus, areaIdx)), areaIdx);
	}

	function clearGhostCable(): void {
		uiStore.ghostCable = null;
		uiStore.ghostCandidates = [];
		uiStore.ghostCandidateIndex = 0;
	}

	// Cycles the auto-suggest ghost cable to the next-best candidate pair on the same source/target
	// module, wrapping back to the first (best) candidate after the last.
	function cycleGhostCable(): void {
		const candidates = uiStore.ghostCandidates;
		if (candidates.length < 2 || !uiStore.ghostCable) return;
		uiStore.ghostCandidateIndex = (uiStore.ghostCandidateIndex + 1) % candidates.length;
		uiStore.ghostCable = { area: uiStore.ghostCable.area, ...candidates[uiStore.ghostCandidateIndex] };
	}

	async function confirmGhostCable(): Promise<void> {
		const ghost = uiStore.ghostCable;
		if (!ghost || !isGhostJack(ghost.to)) return; // a live-preview ghost (to = mouse point) has nothing to confirm here
		clearGhostCable();
		const old = ghost.replaces;
		if (old) {
			const cable = (p: GhostPair): Cable => ({
				colour: old.colour,
				userColour: old.userColour,
				smod: p.from.moduleIndex,
				scon: p.from.connectorIndex,
				dir: 1,
				dmod: p.to.moduleIndex,
				dcon: p.to.connectorIndex,
			});
			const newCables = [cable({ from: ghost.from, to: ghost.to }), ...(ghost.extra ? [cable(ghost.extra)] : [])];
			await slotsStore.replaceCable(old, newCables, ghost.area === 1 ? 'voice' : 'fx');
			return;
		}
		await connectJacks({ ...ghost.from, area: ghost.area }, { ...ghost.to, area: ghost.area });
		if (ghost.extra) await connectJacks({ ...ghost.extra.from, area: ghost.area }, { ...ghost.extra.to, area: ghost.area });
	}

	return { computeGhostSuggestion, suggestAfterDelete, clearGhostCable, cycleGhostCable, confirmGhostCable };
}
